"""Compiles the renderer's HLSL shaders for every SDL_gpu backend and writes
them as C byte arrays to generated/shaders.h (checked in, so building the
renderer needs no shader tools).

Tools (none are needed at build time):
  DXIL  (Direct3D 12): dxc from the Windows SDK (signs the output via dxil.dll)
  SPIR-V (Vulkan):     dxc from the Vulkan SDK (-spirv)
  MSL   (Metal):       spirv-cross from the Vulkan SDK (--msl), from the SPIR-V

Usage: python build_shaders.py [--dxc-dxil PATH] [--dxc-spirv PATH] [--spirv-cross PATH]
"""

import argparse
import glob
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))

SHADERS = [
    # (source, stage, symbol)
    ("quad.vert.hlsl", "vs", "quad_vert"),
    ("blit.frag.hlsl", "ps", "blit_frag"),
    ("resolve.frag.hlsl", "ps", "resolve_frag"),
]


def find_tool(explicit, patterns):
    if explicit:
        return explicit
    for p in patterns:
        hits = sorted(glob.glob(p))
        if hits:
            return hits[-1]
    return None


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(" ".join(cmd) + "\n" + r.stdout + r.stderr)
        sys.exit(1)


def as_array(name, data):
    lines = ["static const unsigned char %s[] = {" % name]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append("static const unsigned int %s_size = %d;" % (name, len(data)))
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dxc-dxil")
    ap.add_argument("--dxc-spirv")
    ap.add_argument("--spirv-cross")
    a = ap.parse_args()
    dxc_dxil = find_tool(a.dxc_dxil, [r"C:\Program Files (x86)\Windows Kits\10\bin\*\x64\dxc.exe"])
    dxc_spirv = find_tool(a.dxc_spirv, [r"C:\VulkanSDK\*\Bin\dxc.exe", "/usr/bin/dxc", "/usr/local/bin/dxc"])
    cross = find_tool(a.spirv_cross, [r"C:\VulkanSDK\*\Bin\spirv-cross.exe", "/usr/bin/spirv-cross", "/usr/local/bin/spirv-cross"])
    if not (dxc_dxil and dxc_spirv and cross):
        sys.exit("missing tools: dxc (DXIL) %s, dxc (SPIR-V) %s, spirv-cross %s" % (dxc_dxil, dxc_spirv, cross))

    out = ["// Generated by build_shaders.py from the .hlsl files next to it. Do not edit.", "#pragma once", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for src, stage, sym in SHADERS:
            path = os.path.join(HERE, src)
            profile = stage + "_6_0"
            dxil = os.path.join(tmp, sym + ".dxil")
            spv = os.path.join(tmp, sym + ".spv")
            msl = os.path.join(tmp, sym + ".msl")
            run([dxc_dxil, "-nologo", "-T", profile, "-E", "main", "-Fo", dxil, path])
            run([dxc_spirv, "-nologo", "-spirv", "-fspv-target-env=vulkan1.0", "-T", profile, "-E", "main", "-Fo", spv, path])
            run([cross, "--msl", "--msl-version", "20100", "--output", msl, spv])
            for ext, file in (("dxil", dxil), ("spirv", spv), ("msl", msl)):
                with open(file, "rb") as f:
                    data = f.read()
                if ext == "msl":
                    data += b"\0"
                out.append(as_array("%s_%s" % (sym, ext), data))
                out.append("")
    gen = os.path.join(HERE, "generated")
    os.makedirs(gen, exist_ok=True)
    with open(os.path.join(gen, "shaders.h"), "w", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", os.path.join(gen, "shaders.h"))


if __name__ == "__main__":
    main()
