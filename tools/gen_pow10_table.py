"""Generate ta_compat/src/pow10_table.inc.

12-byte power-of-ten entries in the layout used by the 1998 C runtime's
string-to-float conversion: bytes 0-1 hold the low 16 bits of 10^p rounded to
an 80-bit mantissa, bytes 2-9 hold 10^p rounded to a 64-bit mantissa, bytes
10-11 the biased exponent. Entries: 10^(d * 8^g) for g = 0..3, d = 1..7, plus
10^4096; positive table then negative table (29 entries each).
"""
from fractions import Fraction
import pathlib


def round_nearest_even(x: Fraction) -> int:
    f = x.numerator // x.denominator
    r = x - f
    return f + 1 if (r > Fraction(1, 2) or (r == Fraction(1, 2) and f & 1)) else f


def entry(p: int) -> bytes:
    x = Fraction(10) ** p
    e2 = x.numerator.bit_length() - x.denominator.bit_length()
    if Fraction(2) ** e2 > x:
        e2 -= 1
    if Fraction(2) ** (e2 + 1) <= x:
        e2 += 1
    norm = x / Fraction(2) ** e2  # in [1, 2)
    m64 = round_nearest_even(norm * (1 << 63))
    lo16 = round_nearest_even(norm * (1 << 79)) & 0xFFFF
    exp = e2 + 0x3FFF
    if m64 >> 64:
        m64 >>= 1
        exp += 1
    return lo16.to_bytes(2, "little") + m64.to_bytes(8, "little") + exp.to_bytes(2, "little")


def powers(sign: int):
    for g in range(5):
        for d in range(1, 8 if g < 4 else 2):
            yield sign * d * 8 ** g


lines = []
for sign in (1, -1):
    for p in powers(sign):
        b = entry(p)
        lines.append("{" + ", ".join(f"0x{v:02X}" for v in b) + f"}},  // 1e{p}")

out = pathlib.Path(__file__).resolve().parent.parent / "ta_compat/src/pow10_table.inc"
out.write_text(
    "// Generated by tools/gen_pow10_table.py - do not edit.\n" + "\n".join(lines) + "\n",
    newline="\n",
)
print(f"wrote {out} ({len(lines)} entries)")
